int rda5815m_tune(it9300 *bridge, uint8_t addr,
                  uint32_t frequency_khz, uint32_t symbol_rate_ksps,
                  int loop_through)
{
    uint32_t frequency_word;
    uint8_t bandwidth;
    int rc;

    if (frequency_khz < 250000u || frequency_khz > 2300000u)
        return -1;

    /* Native driver: MHz * 2^21 / 27 MHz, rounded by constant 0x12f68. */
    frequency_word = (frequency_khz / 1000u) * 0x12f68u;
    if (symbol_rate_ksps <= 3999u)
        bandwidth = 0x44;
    else {
        uint32_t mhz = symbol_rate_ksps / 1000u;
        if (mhz > 0x28u) mhz = 0x28u;
        bandwidth = (uint8_t)(0x40u | mhz);
    }

    if ((rc = write_reg(bridge, addr, 0x04, loop_through ? 0xc1 : 0xe1)) != 0 ||
        (rc = write_reg(bridge, addr, 0x2b, 0x95)) != 0 ||
        (rc = write_reg(bridge, addr, 0x07, (uint8_t)(frequency_word >> 24))) != 0 ||
        (rc = write_reg(bridge, addr, 0x08, (uint8_t)(frequency_word >> 16))) != 0 ||
        (rc = write_reg(bridge, addr, 0x09, (uint8_t)(frequency_word >> 8))) != 0 ||
        (rc = write_reg(bridge, addr, 0x0a, (uint8_t)frequency_word)) != 0 ||
        (rc = write_reg(bridge, addr, 0x0b, bandwidth)) != 0 ||
        (rc = write_reg(bridge, addr, 0x04, loop_through ? 0xc3 : 0xe3)) != 0 ||
        (rc = write_reg(bridge, addr, 0x2b, 0x97)) != 0)
        return rc;
    dtv_sleep_ms(5);
    return 0;
}
